import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from "pdf-lib";
import { formatPaise } from "../recon/money";
import { CATEGORY_INFO, CATEGORY_ORDER, FLAG_LABEL, REVIEW_LABEL, isCategory } from "../recon/labels";
import { REPORT_DISCLAIMER, sideTotal, type ReportData } from "./types";

/**
 * Builds the PDF reconciliation report. Pure: data in, bytes out.
 * Uses the standard Helvetica fonts (no font files to ship); characters they
 * cannot draw are replaced with plain equivalents, e.g. ₹ -> "Rs.".
 */

const PAGE_W = 842; // A4 landscape
const PAGE_H = 595;
const M = 36;
const NAVY = rgb(0.039, 0.071, 0.157);
const INDIGO = rgb(0.31, 0.275, 0.898);
const INK = rgb(0.06, 0.09, 0.16);
const MUTED = rgb(0.39, 0.45, 0.55);
const LINE = rgb(0.886, 0.91, 0.94);
const ROSE = rgb(0.75, 0.07, 0.24);
const SURFACE = rgb(0.973, 0.98, 0.988);

export const PDF_MAX_LINES = 1000;

/** Map text to what the standard (WinAnsi) fonts can draw. */
export function pdfSafe(text: string): string {
  return text
    .replace(/₹/g, "Rs.")
    .replace(/→/g, "->")
    .replace(/≥/g, ">=")
    .replace(/≤/g, "<=")
    .replace(/×/g, "x")
    .replace(/[‐-‒]/g, "-")
    .replace(/[^\x20-\x7E -ÿ–—‘’“”•…]/g, "?");
}

function fit(text: string, font: PDFFont, size: number, width: number): string {
  let t = pdfSafe(text);
  if (font.widthOfTextAtSize(t, size) <= width) return t;
  while (t.length > 1 && font.widthOfTextAtSize(`${t}…`, size) > width) t = t.slice(0, -1);
  return `${t}…`;
}

function wrap(text: string, font: PDFFont, size: number, width: number): string[] {
  const words = pdfSafe(text).split(/\s+/);
  const lines: string[] = [];
  let line = "";
  for (const w of words) {
    const next = line ? `${line} ${w}` : w;
    if (font.widthOfTextAtSize(next, size) > width && line) {
      lines.push(line);
      line = w;
    } else {
      line = next;
    }
  }
  if (line) lines.push(line);
  return lines;
}

const istDateTime = (d: Date) =>
  new Intl.DateTimeFormat("en-IN", { dateStyle: "medium", timeStyle: "short", timeZone: "Asia/Kolkata" }).format(d) + " IST";

type Col = { title: string; width: number; align?: "right" };

export async function buildReportPdf(data: ReportData): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(pdfSafe(`GST reconciliation - ${data.client.name} - ${data.periodLabel}`));
  doc.setAuthor("Taxora");
  doc.setCreator("Taxora");
  doc.setCreationDate(data.generatedAt);
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);

  let page!: PDFPage;
  let y = 0;

  const text = (s: string, x: number, yy: number, size = 9, f = font, color = INK) =>
    page.drawText(pdfSafe(s), { x, y: yy, size, font: f, color });

  const newPage = (withBand: boolean) => {
    page = doc.addPage([PAGE_W, PAGE_H]);
    if (withBand) {
      page.drawRectangle({ x: 0, y: PAGE_H - 56, width: PAGE_W, height: 56, color: NAVY });
      page.drawRectangle({ x: M, y: PAGE_H - 40, width: 22, height: 22, color: INDIGO });
      text("T", M + 7, PAGE_H - 34, 14, bold, rgb(1, 1, 1));
      text("Taxora", M + 30, PAGE_H - 35, 15, bold, rgb(1, 1, 1));
      text("GST Reconciliation Report", PAGE_W - M - bold.widthOfTextAtSize("GST Reconciliation Report", 12), PAGE_H - 34, 12, bold, rgb(1, 1, 1));
      y = PAGE_H - 80;
    } else {
      text(fit(`${data.client.name} · ${data.periodLabel}`, font, 8, 500), M, PAGE_H - 24, 8, font, MUTED);
      page.drawLine({ start: { x: M, y: PAGE_H - 30 }, end: { x: PAGE_W - M, y: PAGE_H - 30 }, thickness: 0.5, color: LINE });
      y = PAGE_H - 48;
    }
  };

  const ensure = (needed: number, onBreak?: () => void) => {
    if (y - needed < M + 30) {
      newPage(false);
      onBreak?.();
    }
  };

  // ── Cover / meta ──
  newPage(true);
  text(data.client.name, M, y, 18, bold);
  y -= 18;
  const metaLeft = [
    ["Client GSTIN", data.client.gstin ?? "Unregistered"],
    ["Tax period", data.periodLabel],
    ["Workspace", data.workspaceName],
  ];
  const metaRight = [
    ["Generated", istDateTime(data.generatedAt)],
    ["Generated by", data.generatedBy],
    ["Status", data.finalizedAt ? `Finalised ${istDateTime(data.finalizedAt)}${data.finalizedBy ? ` by ${data.finalizedBy}` : ""}` : "Not finalised (draft review)"],
  ];
  for (let i = 0; i < 3; i++) {
    y -= 14;
    text(metaLeft[i][0], M, y, 8, font, MUTED);
    text(fit(metaLeft[i][1], bold, 9, 280), M + 80, y, 9, bold);
    text(metaRight[i][0], 430, y, 8, font, MUTED);
    text(fit(metaRight[i][1], bold, 9, 300), 510, y, 9, bold);
  }
  if (data.filterLabel) {
    y -= 18;
    text(`Filtered report: ${data.filterLabel}`, M, y, 9, bold, INDIGO);
  }

  // ── Summary ──
  y -= 28;
  text("Summary", M, y, 12, bold);
  y -= 8;
  const boxW = (PAGE_W - 2 * M - 6 * 8) / 7;
  CATEGORY_ORDER.forEach((c, i) => {
    const x = M + i * (boxW + 8);
    page.drawRectangle({ x, y: y - 46, width: boxW, height: 46, borderColor: LINE, borderWidth: 0.75, color: SURFACE });
    text(fit(CATEGORY_INFO[c].label, font, 7.5, boxW - 12), x + 6, y - 14, 7.5, font, MUTED);
    text(String(data.counts.byCategory[c] ?? 0), x + 6, y - 36, 16, bold);
  });
  y -= 62;
  text(
    `${data.counts.prRecords} purchase-register records and ${data.counts.gstr2bRecords} GSTR-2B records were reconciled. ` +
      `${data.counts.needsReview} result(s) need review; ${data.counts.pendingReview} are still pending.`,
    M,
    y,
    9,
  );
  if (data.importIssueTotal > 0) {
    y -= 13;
    text(`${data.importIssueTotal} uploaded row(s) had errors and were excluded from matching (listed in the Excel report).`, M, y, 9, font, ROSE);
  }

  // ── Detail table: everything that is not an exact match ──
  const detail = data.lines.filter((l) => l.category !== "EXACT");
  const shown = detail.slice(0, PDF_MAX_LINES);
  y -= 28;
  text("Items for review", M, y, 12, bold);
  text(
    `Exact matches (${data.counts.byCategory.EXACT ?? 0}) are listed in the Excel report only.`,
    M + 110,
    y + 1,
    8,
    font,
    MUTED,
  );
  y -= 10;

  const cols: Col[] = [
    { title: "Result", width: 58 },
    { title: "Supplier GSTIN", width: 86 },
    { title: "Purchase register", width: 106 },
    { title: "GSTR-2B", width: 106 },
    { title: "PR total (Rs.)", width: 66, align: "right" },
    { title: "2B total (Rs.)", width: 66, align: "right" },
    { title: "Difference", width: 60, align: "right" },
    { title: "Review", width: 62 },
    { title: "Reason", width: PAGE_W - 2 * M - 610 },
  ];
  const drawHeader = () => {
    page.drawRectangle({ x: M, y: y - 16, width: PAGE_W - 2 * M, height: 16, color: SURFACE });
    let x = M + 4;
    for (const c of cols) {
      const w = bold.widthOfTextAtSize(c.title, 7.5);
      text(c.title, c.align === "right" ? x + c.width - 8 - w : x, y - 11, 7.5, bold, MUTED);
      x += c.width;
    }
    y -= 18;
  };

  if (shown.length === 0) {
    y -= 6;
    text("Nothing needs review: every record was an exact match.", M, y, 9, font, MUTED);
  } else {
    drawHeader();
    for (const l of shown) {
      ensure(16, drawHeader);
      const cells = [
        isCategory(l.category) ? CATEGORY_INFO[l.category].short : l.category,
        (l.pr ?? l.b2b)?.gstin ?? "",
        l.pr ? `${l.pr.invoiceNo} · ${l.pr.invoiceDate ?? "no date"}` : "—",
        l.b2b ? `${l.b2b.invoiceNo} · ${l.b2b.invoiceDate ?? "no date"}` : "—",
        l.pr ? formatPaise(sideTotal(l.pr)!) : "—",
        l.b2b ? formatPaise(sideTotal(l.b2b)!) : "—",
        l.diffTotal === null ? "—" : formatPaise(l.diffTotal),
        l.needsReview ? REVIEW_LABEL[l.reviewStatus] : "—",
        [l.flags.map((f) => FLAG_LABEL[f] ?? f).join(", "), l.reason].filter(Boolean).join(" — "),
      ];
      let x = M + 4;
      cells.forEach((cell, i) => {
        const c = cols[i];
        const isDiff = i === 6 && l.diffTotal !== null && Math.abs(l.diffTotal) > 100;
        const t = fit(cell, font, 7.5, c.width - 8);
        const w = font.widthOfTextAtSize(t, 7.5);
        text(t, c.align === "right" ? x + c.width - 8 - w : x, y - 10, 7.5, isDiff ? bold : font, isDiff ? ROSE : INK);
        x += c.width;
      });
      page.drawLine({ start: { x: M, y: y - 14 }, end: { x: PAGE_W - M, y: y - 14 }, thickness: 0.4, color: LINE });
      y -= 15;
    }
    if (detail.length > shown.length) {
      y -= 8;
      text(`Showing the first ${PDF_MAX_LINES.toLocaleString("en-IN")} of ${detail.length.toLocaleString("en-IN")} items. The Excel report contains all of them.`, M, y, 8, font, MUTED);
    }
  }

  // ── Disclaimer ──
  const lines = wrap(REPORT_DISCLAIMER, font, 8, PAGE_W - 2 * M);
  ensure(lines.length * 11 + 24);
  y -= 22;
  text("Important", M, y, 9, bold);
  for (const line of lines) {
    y -= 11;
    text(line, M, y, 8, font, MUTED);
  }

  // ── Footers with page numbers ──
  const pages = doc.getPages();
  pages.forEach((p, i) => {
    const footer = pdfSafe(`Generated by Taxora · ${istDateTime(data.generatedAt)}`);
    p.drawText(footer, { x: M, y: 18, size: 7.5, font, color: MUTED });
    const num = `Page ${i + 1} of ${pages.length}`;
    p.drawText(num, { x: PAGE_W - M - font.widthOfTextAtSize(num, 7.5), y: 18, size: 7.5, font, color: MUTED });
  });

  return doc.save();
}
