import { CircleAlert, Sparkles } from "lucide-react";
import { formatDateTime } from "@/lib/format";
import { SubmitButton } from "@/app/(app)/reconciliation/[id]/submit-button";

/**
 * Frame for AI output. Every suggestion is labelled as such, with the model and
 * time it came from; nothing here is presented as a conclusion.
 */
export function AiPanel(props: {
  title: string;
  configured: boolean;
  error?: string;
  generated: { model: string; createdAt: Date } | null;
  action: (formData: FormData) => Promise<void>;
  hidden: Record<string, string>;
  buttonText: string;
  children?: React.ReactNode;
}) {
  return (
    <section className="rounded-xl border border-violet-200 bg-violet-50/40 p-5">
      <div className="flex flex-col gap-3 sm:flex-row sm:items-start sm:justify-between">
        <div>
          <h2 className="flex items-center gap-2 font-semibold text-ink">
            <Sparkles className="h-4 w-4 text-violet-600" aria-hidden="true" />
            {props.title}
          </h2>
          <p className="mt-1 text-xs text-slate-600">
            AI suggestion — verify before relying on it. It never decides eligibility of input tax credit and does not change any result.
          </p>
        </div>
        {props.configured ? (
          <form action={props.action}>
            {Object.entries(props.hidden).map(([k, v]) => <input key={k} type="hidden" name={k} value={v} />)}
            <SubmitButton
              pendingText="Asking…"
              className="inline-flex items-center gap-2 rounded-lg bg-white px-3 py-2 text-sm font-semibold text-violet-800 ring-1 ring-inset ring-violet-300 hover:bg-violet-50 disabled:opacity-60"
            >
              {props.generated ? "Ask again" : props.buttonText}
            </SubmitButton>
          </form>
        ) : (
          <p className="text-xs text-muted sm:max-w-56 sm:text-right">Not configured on this server. Add ANTHROPIC_API_KEY to enable it (see Settings → Integrations).</p>
        )}
      </div>

      {props.error && (
        <p role="alert" className="mt-3 flex items-start gap-2 rounded-lg bg-rose-50 px-3 py-2 text-sm text-rose-800">
          <CircleAlert className="mt-0.5 h-4 w-4 shrink-0" aria-hidden="true" />{props.error}
        </p>
      )}

      {props.generated && (
        <div className="mt-4 space-y-3 text-sm text-slate-800">
          {props.children}
          <p className="text-xs text-muted">Generated by {props.generated.model} · {formatDateTime(props.generated.createdAt)}</p>
        </div>
      )}
    </section>
  );
}

export const LIKELIHOOD_LABEL = { high: "More likely", medium: "Possible", low: "Less likely" } as const;
